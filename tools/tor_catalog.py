"""Regenerate the external Tor Browser code catalog from the authenticated release.

Developer-only: needs GnuPG and 7z. Not called by normal builds, no Tor engine is
redistributed. Uses a dedicated keyring; no changes to the user's GnuPG keyring.
"""
from pathlib import Path, PurePosixPath
import argparse
import hashlib
import json
import subprocess
import urllib.request
import uuid

ROOT = Path(__file__).resolve().parents[1]

def main(gpg,seven_zip):
    lock=json.loads((ROOT/'tor-browser.lock.json').read_text())
    if not lock['package_url'].startswith('https://dist.torproject.org/torbrowser/'):
        raise ValueError('Official HTTPS package URL required')
    work=ROOT/'.deps/tor-qa';work.mkdir(exist_ok=True)
    name=lock['package_url'].rsplit('/',1)[1]
    for filename,url,limit in [(name,lock['package_url'],128*1024*1024),
        (name+'.asc',lock['package_url']+'.asc',65536),('tor-browser-key.asc',lock['key_url'],1024*1024)]:
        target=work/filename
        if not target.exists():
            with urllib.request.urlopen(url,timeout=60) as source,target.open('xb') as sink:
                size=0
                while chunk:=source.read(1024*1024):
                    size+=len(chunk)
                    if size>limit:raise ValueError('Download size limit exceeded')
                    sink.write(chunk)
    package=work/name
    if package.stat().st_size!=lock['package_bytes'] or hashlib.sha256(package.read_bytes()).hexdigest()!=lock['package_sha256']:
        raise ValueError('Pinned package size/SHA256 mismatch')
    # Keep the dedicated home short: MSYS GnuPG's agent socket path has a limit.
    home='g'+uuid.uuid4().hex[:8];(work/home).mkdir()
    def signature_command(*args):
        # Relative arguments also work with the MSYS GnuPG shipped in Git for Windows.
        result=subprocess.run([gpg,'--homedir',home,'--batch',*args],cwd=work,capture_output=True,text=True,timeout=60)
        if result.returncode:raise RuntimeError(result.stderr)
        return {'stdout':result.stdout,'stderr':result.stderr}
    signature_command('--import','tor-browser-key.asc')
    fingerprint=signature_command('--with-colons','--fingerprint',lock['primary_fingerprint'])
    if 'fpr:::::::::'+lock['primary_fingerprint']+':' not in fingerprint['stdout']:
        raise ValueError('Official primary key fingerprint missing')
    signature=signature_command('--status-fd','1','--verify',name+'.asc',name)
    valid=[line.split() for line in signature['stdout'].splitlines() if line.startswith('[GNUPG:] VALIDSIG ')]
    if len(valid)!=1 or valid[0][2]!=lock['signing_subkey'] or valid[0][-1]!=lock['primary_fingerprint']:
        raise ValueError('Pinned release signature/subkey mismatch')
    listing=subprocess.run([seven_zip,'l','-slt','-sccUTF-8',str(package)],capture_output=True,text=True,encoding='utf-8',check=True,timeout=30).stdout
    # The 7z NSIS listing includes PE/NSIS container metadata before the separator.
    contents=listing.rsplit('----------',1)[-1]
    for line in contents.splitlines():
        if line.startswith('Path = '):
            path=PurePosixPath(line[7:].replace('\\','/'))
            if path.is_absolute() or '..' in path.parts or any(':' in part for part in path.parts):
                raise ValueError('Unsafe package member')
    extracted=work/('catalog-extracted-'+uuid.uuid4().hex);extracted.mkdir()
    subprocess.run([seven_zip,'x',str(package),'-o'+str(extracted),'-y'],check=True,capture_output=True,timeout=120)
    records=[];total=0
    for file in sorted((extracted/'Browser').rglob('*')):
        if file.is_symlink():raise ValueError('Unexpected link in authenticated package')
        if not file.is_file():continue
        relative=file.relative_to(extracted).as_posix()
        if relative.startswith('Browser/TorBrowser/Data/'):continue
        if len(relative)>512 or not all(32<=ord(c)<127 for c in relative) or '"' in relative:
            raise ValueError('Unsupported catalog path')
        data=file.read_bytes();total+=len(data)
        records.append({'name':relative,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
    if not 100<=len(records)<=512 or total>512*1024*1024:raise ValueError('Catalog budget mismatch')
    text=['// Generated by tools/tor_catalog.py from the pinned, PGP-verified official package.',
          '// Excludes mutable Tor Browser profile/Data. No Tor binaries are redistributed.',
          'static constexpr CatalogFile kTorCatalog[] = {']
    for record in records:
        path=record['name'].replace('/','\\').replace('\\','\\\\')
        text.append(f'  {{L"{path}", {record["bytes"]}, "{record["sha256"]}"}},')
    text+=['};','']
    (ROOT/'src/privacy/tor_catalog.inc').write_text('\n'.join(text),encoding='utf-8')
    evidence={'lock':lock,'signature':signature,'files':len(records),'bytes':total,'catalog':records}
    (ROOT/'artifacts/tor-catalog-verification.json').write_text(json.dumps(evidence,indent=2)+'\n')
    print(f'Authenticated Tor Browser {lock["version"]}: {len(records)} catalog files, {total} bytes')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gpg',default='gpg');parser.add_argument('--7z',dest='seven_zip',default='7z')
    args=parser.parse_args();main(args.gpg,args.seven_zip)
